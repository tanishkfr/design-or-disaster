// Use the actual sequential Tab order, not programmatic focus or pointer clicks.
async function tabTo(locator) {
  await locator.waitFor()
  for (let i = 0; i < 180; i++) {
    if (await locator.evaluate((el) => el === document.activeElement)) return
    await page.keyboard.press('Tab')
  }
  throw new Error('Unreachable by Tab: ' + await locator.getAttribute('aria-label'))
}
async function activate(locator) { await tabTo(locator); await page.keyboard.press('Enter') }
const button = (name) => page.getByRole('button', { name, exact: true })
async function type(locator, value) {
  await tabTo(locator)
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText(value)
}
